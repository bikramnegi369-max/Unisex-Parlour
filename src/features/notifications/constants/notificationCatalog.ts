export const EVENT_META_BY_TYPE: Record<string, NotificationEventMeta> =
  Object.fromEntries(NOTIFICATION_EVENT_CATALOG.map((item) => [item.eventType, item]));

export function getEventLabel(eventType: string): string {
  return EVENT_META_BY_TYPE[eventType]?.label ?? eventType;
}

export function getSampleVariables(eventType: string): Record<string, string> {
  const meta = EVENT_META_BY_TYPE[eventType];
  if (!meta) return { brandName: VARIABLE_META.brandName.sampleValue };
  return Object.fromEntries(meta.variables.map((v) => [v.key, v.sampleValue]));
}
